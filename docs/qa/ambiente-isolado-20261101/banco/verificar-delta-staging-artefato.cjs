// Somente artefatos; nenhum banco, processo SQL ou rede.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const ler = nome => fs.readFileSync(path.join(__dirname,nome),'utf8');
const sha = x => crypto.createHash('sha256').update(x).digest('hex');
assert(fs.existsSync(path.join(__dirname,'03-delta-operacional-staging.sql')), 'Variante explícita staging ainda não preparada');
const manifesto = JSON.parse(ler('delta-staging-manifesto.json'));
const original = ler('../../migracoes-capacidade-20261031/02-delta-operacional.sql');
assert.equal(sha(original),'1619e78b9155ba9443b6080fa7d082f3c335d8e8b07015d5d894462149df4c94');
assert.equal(sha(ler('catalogo-prekit-staging.json')),'5c607e56e58e7aa7b67d16baee150f26ff05e2b599809645777a12f6af51b9ad');
const variante=ler('03-delta-operacional-staging.sql');
assert(variante.startsWith(manifesto.cabecalhoVariante));
const corpo=variante.slice(manifesto.cabecalhoVariante.length);
assert.equal(corpo.replace("md5(observado::text)<>'8abc338413ff0c60770d3aea1c3413d1'","md5(observado::text)<>'4550d262d2f09edec1efd68b4c699f67'"),original,'Única diferença executável deve ser o fingerprint da guarda');
assert.equal((corpo.match(/8abc338413ff0c60770d3aea1c3413d1/g)||[]).length,1);
assert(corpo.includes("raise exception 'Bucket privado obrigatório'"));
const readonly=ler('05-verificar-prekit-somente-leitura.sql');
assert(readonly.includes('begin read only;')&&readonly.includes('PREKIT_STAGING_CONFIRMADO'));
assert(!/^\s*(create|alter|insert|update|delete|drop|truncate|grant|revoke)\b/im.test(readonly));
const rollback=ler('04-ensaiar-delta-com-rollback-staging.sql');
assert.equal(rollback,manifesto.cabecalhoRollback+variante.replace(/\ncommit;\s*$/,'\nrollback;\n')+'\n'+readonly,'Ensaio só troca COMMIT por ROLLBACK e acrescenta conferência readonly');
const pos=ler('06-verificar-posdelta-somente-leitura.sql');
const gates=original.slice(original.indexOf('-- Gate integral homologado, sem mudanças.'),original.lastIndexOf("notify pgrst,'reload schema';"));
assert(pos.includes(gates),'Gates originais precisam ser idênticos');
assert(pos.includes('begin read only;')&&pos.includes('DELTA_STAGING_GATES_OK'));
assert(!/^\s*(create|alter|insert|update|delete|drop|truncate|grant|revoke)\b/im.test(pos));
for (const [nome,hash] of Object.entries(manifesto.arquivos)) assert.equal(sha(ler(nome)),hash,'Arquivo alterado: '+nome);
console.log(JSON.stringify({aprovado:true,sqlExecutado:false,originalImutavel:true,payloadEGatesIdenticos:true,varianteSha256:sha(variante),ensaioRollbackSha256:sha(rollback)}));
